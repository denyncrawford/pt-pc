import assert from 'node:assert/strict';
import {readFileSync,openAsBlob,writeFileSync} from 'node:fs';
const [url,pkgPath,manifestPath]=process.argv.slice(2);
if(!url||!pkgPath||!manifestPath)throw new Error('Usage: node integration.mjs <server-url> <pkg> <expected-manifest.json>');
const base=new URL(url);const req=(path: string,opts?: RequestInit)=>fetch(new URL(path,base),opts);
assert.equal((await req('api/status')).status,200);
assert.equal((await fetch(base.origin+'/api/status')).status,404);
assert.equal((await req('api/status',{headers:{Origin:'https://example.org'}})).status,403);
assert.equal((await req('api/pkg',{method:'POST',body:'bad'})).status,415);
assert.equal((await req('api/pkg',{method:'POST',headers:{'Content-Type':'application/octet-stream'},body:new Uint8Array(4096)})).status,400);
assert.equal((await req('assets/../Program.cs')).status,404);
console.log('PASS: API, authorization, invalid package, path allowlist');
const blob=await openAsBlob(pkgPath);
const result=await req('api/pkg',{method:'POST',headers:{'Content-Type':'application/octet-stream'},body:blob});
assert.equal(result.status,200,await result.text());
const head=await req('assets/chunk1.psarc',{method:'HEAD'});assert.equal(head.status,200);
const partial=await req('assets/chunk1.psarc',{headers:{Range:'bytes=0-31'}});assert.equal(partial.status,206);assert.equal((await partial.arrayBuffer()).byteLength,32);
const bad=await req('assets/chunk1.psarc',{headers:{Range:'bytes=99999999999-'}});assert.equal(bad.status,416);
const changed=await req('assets/chunk1.psarc',{headers:{Range:'bytes=0-31','If-Match':'"stale"'}});assert.equal(changed.status,412);
const manifest=await (await req('assets/manifest.json')).json();
const original=JSON.parse(readFileSync(manifestPath,'utf8'));
assert.deepEqual(manifest.files,original.files);
console.log('PASS: real PKG import, matching hashes, HTTP 206/416/412');
